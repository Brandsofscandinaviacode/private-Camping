export type Locale = "da" | "en" | "de";
export const ALL_LOCALES: Locale[] = ["da", "en", "de"];

export const localeLabels: Record<Locale, string> = {
  da: "Dansk",
  en: "English",
  de: "Deutsch",
};

export function detectLocale(): Locale {
  if (typeof window === "undefined") return "da";
  const saved = localStorage.getItem("campsense-lang") as Locale;
  if (saved && ALL_LOCALES.includes(saved)) return saved;
  const browserLang = navigator.language.slice(0, 2);
  if (browserLang === "de") return "de";
  if (browserLang === "en") return "en";
  return "da";
}

export function persistLocale(l: Locale) {
  localStorage.setItem("campsense-lang", l);
}

